def universe_verdict(sub_industry: str, sector: str) -> str:
    """S2 Universe Applicability Rule.
    Returns 'NOT_APPLICABLE' for banks, insurance, capital markets, consumer finance,
    mortgage finance, and REITs.
    Returns 'NOT_APPLICABLE_FALLBACK' (fail CLOSED) if sub_industry is unrecognized
    AND sector is Financials or Real Estate.
    Returns 'SCORED' otherwise."""
    sub = (sub_industry or "").strip()
    sec = (sector or "").strip()

    if sub in EXCLUDED_SUB_INDUSTRIES:
        return "NOT_APPLICABLE"

    if sub in ("Transaction & Payment Processing Services", "Financial Exchanges & Data"):
        return "SCORED"

    if sub not in GICS_SUBIND_TO_IND:
        if sec in ("Financials", "Real Estate"):
            return "NOT_APPLICABLE_FALLBACK"

    return "SCORED"
